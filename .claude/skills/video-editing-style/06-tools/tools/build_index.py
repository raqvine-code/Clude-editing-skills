#!/usr/bin/env python3
"""Rebuild INDEX.md and check the structure of this editing brain.

Run after ANY change to a skill (new, renamed, moved):
    python3 -I 06-tools/tools/build_index.py            (from the brain root)
    python3 -I /path/to/06-tools/tools/build_index.py /path/to/brain-root

Writes INDEX.md at the brain root, then lints:
  1. every skill folder has GUIDE.md with `name` = folder name and a `description`
  2. every backticked path that starts with a layer folder (01-process/ ... 08-learning-log/)
     points to a file or folder that exists
Exit code 1 if anything is wrong.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(HERE))

LAYERS = [
    ("02-craft", "Craft: how to build any edit (method, motion graphics, text moves)"),
    ("03-sound-type-assets", "Sound, type and assets (SFX / music, fonts, B-roll and PNG catalogs, thumbnails)"),
    ("04-styles", "Style library: pick ONE style for the video"),
    ("05-clients", "Clients: rules that belong to one client only"),
    ("06-tools", "Tools and learning (watch a video, After Effects rebuild, save a lesson)"),
]
LAYER_NAMES = ("01-process", "02-craft", "03-sound-type-assets", "04-styles", "05-clients",
               "06-tools", "07-edit-kit-reference", "08-learning-log")


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}, text
    fm = {}
    for line in m.group(1).split("\n"):
        k, _, v = line.partition(":")
        if _:
            fm[k.strip()] = v.strip().strip('"').strip("'")
    return fm, text[m.end():]


def scope_of(body):
    """Read the `> **Scope: kind (who). ...` banner under the frontmatter; no banner = universal."""
    m = re.search(r"^> \*\*Scope: ([a-z ]+?)(?: \(([^)]*)\))?[.:]", body[:2000], re.M)
    if not m:
        return "universal"
    kind = m.group(1).strip().replace(" ", "-")
    return f"{kind} ({m.group(2)})" if m.group(2) else kind


def find_skills():
    out = []
    for layer, _ in LAYERS:
        base = os.path.join(ROOT, layer)
        for r, dirs, files in os.walk(base):
            if "GUIDE.md" in files:
                dirs[:] = []  # a skill folder holds no nested skills
                out.append((layer, r))
    return sorted(out, key=lambda x: (x[0], os.path.basename(x[1])))


problems = []
rows = []
for layer, path in find_skills():
    rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
    text = open(os.path.join(path, "GUIDE.md"), encoding="utf-8").read()
    fm, body = frontmatter(text)
    name, desc = fm.get("name", ""), fm.get("description", "")
    if name != os.path.basename(path):
        problems.append(f"{rel}: frontmatter name '{name}' != folder name")
    if not desc:
        problems.append(f"{rel}: missing description")
    rows.append((layer, os.path.basename(path), rel, scope_of(body), desc))

# ---- INDEX.md ----
lines = ["# INDEX: every skill, where it lives, when to use it", "",
         "Generated by `06-tools/tools/build_index.py`. Do not edit by hand; rebuild after any skill change.", "",
         f"{len(rows)} skills in 5 layers. Scope: **universal** (any client), **mixed** (general rules plus one client's taste), "
         "**client** (one client only), **style-reference** (another creator's measured style), **asset-catalog** (list of files kept on the Mac), **tool**.", ""]
for layer, title in LAYERS:
    items = [r for r in rows if r[0] == layer]
    lines += [f"## {layer}/ : {title}", "", "| Skill | Path | Scope | Use when |", "|---|---|---|---|"]
    for _, name, rel, scope, desc in items:
        d = desc.replace("|", "/")
        if len(d) > 200:
            d = d[:197].rsplit(" ", 1)[0] + "..."
        lines.append(f"| `{name}` | `{rel}/GUIDE.md` | {scope} | {d} |")
    lines.append("")
lines += ["## Not skills (read when the router points here)", "",
          "| What | Path |", "|---|---|",
          "| The gate before every edit (reading list, move menu, PRE-EDIT sheet, gate tool) | `01-process/before-edit/README.md` |",
          "| Plan template, master plan, style overviews | `01-process/mastery/` |",
          "| Client bar for Naveen bro | `05-clients/naveen-bro/CLIENT-BAR.md` |",
          "| Edit-Kit (41 open-source skills, text only, vendored unmodified) | `07-edit-kit-reference/` |",
          "| Everything learned, by date | `08-learning-log/CHANGELOG.md` |",
          "| Post-mortem of the rejected video 25 | `08-learning-log/VIDEO-25-POSTMORTEM.md` |",
          "| Original CLAUDE.md, old README, old index | `_archive/` |", ""]
open(os.path.join(ROOT, "INDEX.md"), "w", encoding="utf-8").write("\n".join(lines))

# ---- link lint ----
tok = re.compile(r"`((?:<ROOT>/)?(?:" + "|".join(LAYER_NAMES) + r")/[^`\s]*)`")
checked = 0
for r, dirs, files in os.walk(ROOT):
    rel_r = os.path.relpath(r, ROOT).replace(os.sep, "/")
    if rel_r.startswith(("_archive", "07-edit-kit-reference", "08-learning-log")):
        continue
    for f in files:
        if not f.endswith(".md") or f == "INDEX.md" and r == ROOT:
            continue
        p = os.path.join(r, f)
        for n, line in enumerate(open(p, encoding="utf-8").read().split("\n"), 1):
            for m in tok.finditer(line):
                t = m.group(1).replace("<ROOT>/", "").rstrip(".,;:)")
                if any(c in t for c in "<>*{}$") or "..." in t:
                    continue
                t = t.split("#")[0]
                if t.lower().endswith((".ttf", ".woff2", ".otf")):
                    continue  # fonts are not shipped (only 6 are); see PATHS-AND-SETUP.md
                checked += 1
                if not os.path.exists(os.path.join(ROOT, t)):
                    problems.append(f"{os.path.relpath(p, ROOT)}:{n}: missing path {t}")

print(f"INDEX.md written: {len(rows)} skills; {checked} layer paths checked")
if problems:
    print(f"\n{len(problems)} PROBLEM(S):")
    for x in problems:
        print(" -", x)
    sys.exit(1)
print("OK: structure check passed")
